/** Every plain string in the table (functions are called with sample arguments), for the copy lint. */
export function allStrings(node = COPY, out = []) {
  if (typeof node === "string") out.push(node);
  else if (typeof node === "function") {
    for (const args of [[1, 5], ["Left", "a value"], [12, "1.92"], ["a value"], [3], []]) {
      try { const v = node(...args); if (typeof v === "string") out.push(v); } catch { /* wrong arity for this sample */ }
    }
  } else if (Array.isArray(node)) node.forEach((n) => allStrings(n, out));
  else if (node && typeof node === "object") Object.values(node).forEach((n) => allStrings(n, out));
  return out;
}
